-- Grants for the least-privilege app role. Guarded so self-host without the role still migrates.
-- The ALTER DEFAULT PRIVILEGES FOR ROLE CURRENT_USER clause covers the mastra_* tables that
-- Mastra's PostgresStore creates in this schema at runtime: they are created by the same DB
-- role that runs migrations (both use DATABASE_URL — the migrator/worker/mastraState connection),
-- so future tables it owns automatically grant to seta_app without a follow-up migration.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'seta_app') THEN
    EXECUTE 'GRANT USAGE ON SCHEMA agent TO seta_app';
    EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA agent TO seta_app';
    EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA agent GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO seta_app';
    EXECUTE 'ALTER DEFAULT PRIVILEGES FOR ROLE CURRENT_USER IN SCHEMA agent GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO seta_app';
  END IF;
END $$;
